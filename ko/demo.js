screen?.addEventListener("click", (event) => {
  const target = event.target.closest("[data-action]");
  if (!target) return;
  const action = target.dataset.action;
  const wordId = Number(target.dataset.wordId);
  event.stopPropagation();

  if (action === "open-list") setRoute("list");
  if (action === "open-test") setRoute("test");
  if (action === "open-detail") setRoute("detail", { selectedId: wordId });
  if (action === "toggle-meanings") {
    state.showAllMeanings = !state.showAllMeanings;
    render();
  }
  if (action === "show-meaning") {
    state.progress[wordId].isMeanVisible = true;
    const word = demoWords.find((item) => item.id === wordId);
    const meaningButton = target.closest(".ios-word-main");
    if (word && meaningButton) {
      target.outerHTML = `<small>${word.meaningSimple}</small>`;
    }
  }
  if (action === "toggle-progress") {
    updateProgress(wordId, toggleFlutterLike);
    const progress = state.progress[wordId];
    const size = target.classList.contains("circle") ? "circle" : "square";
    if (size === "circle") {
      target.className = `ios-memory-badge circle ${stage(progress)}`;
      target.style.setProperty("--percent", progress.isMemorized ? progress.memorizedAt : 0);
      target.querySelector("b").textContent = String(Math.min(progress.memorizedCount, 99)).padStart(2, "0");
      target.setAttribute("aria-label", `${stageTitle(progress)}。覚えた回数 ${progress.memorizedCount}`);
    } else {
      target.outerHTML = memoryBadge(progress, size);
    }
  }
  if (action === "set-test-filter") {
    state.testFilter = target.dataset.filter;
    resetTest(true);
    render();
  }
  if (action === "test-tab") {
    state.testBackTab = target.dataset.tab;
    screen.querySelectorAll('[data-action="test-tab"]').forEach((button) => {
      button.classList.toggle("active", button.dataset.tab === state.testBackTab);
    });
    const tabContent = screen.querySelector("[data-test-tab-content]");
    if (tabContent) tabContent.innerHTML = testBackContent(currentWord());
  }
  if (action === "flip-card") {
    state.showBack = true;
    target.classList.add("back-visible");
  }
  if (action === "favorite") {
    state.progress[wordId].isFavorite = !state.progress[wordId].isFavorite;
    target.classList.add("is-favorited");
    target.innerHTML = icon(state.progress[wordId].isFavorite ? "heartFill" : "heart");
  }
  if (action === "sound") {
    target.classList.remove("is-playing");
    window.requestAnimationFrame(() => target.classList.add("is-playing"));
    const word = currentWord();
    playAudio(target.closest(".ios-detail-block") || target.dataset.audioKind === "sentence" ? word.sentenceAudio : word.pronunciationAudio);
  }
  if (action === "answer") answerCurrent(target.dataset.answer);
  if (action === "restart-test") {
    resetTest(true);
    render();
  }
  if (action === "prev-word") {
    const index = demoWords.findIndex((word) => word.id === state.selectedId);
    if (index > 0) state.selectedId = demoWords[index - 1].id;
    render();
  }
  if (action === "next-word") {
    const index = demoWords.findIndex((word) => word.id === state.selectedId);
    if (index < demoWords.length - 1) state.selectedId = demoWords[index + 1].id;
    render();
  }
});

