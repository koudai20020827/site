const testPool = () => {
  const words = demoWords.filter((word) => {
    if (state.testFilter !== "review") return true;
    const progress = state.progress[word.id];
    return !progress.isMemorizedMax && progress.memorizedAt < 100;
  });
  return words;
};

const resetTest = (shuffle = true) => {
  state.testWords = testPool();
  if (shuffle) state.testWords.sort(() => Math.random() - 0.5);
  state.testIndex = 0;
  state.showBack = false;
  state.testBackTab = "meaning";
  state.testCounts = { learning: 0, known: 0, mastered: 0 };
};

