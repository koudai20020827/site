const stage = (progress) => {
  if (progress.isMemorizedMax) return "mastered";
  if (progress.isMemorized) return "retained";
  return "learning";
};

const stageTitle = (progress) => {
  if (progress.isMemorizedMax) return "完全定着";
  if (progress.isMemorized) return "覚えた";
  return "学習中";
};

const partLabel = (part) => {
  if (part === "verb") return "動";
  if (part === "adjective") return "形";
  if (part === "noun") return "名";
  if (part === "adverb") return "副";
  return part;
};

const studyWords = () => demoWords.map((content) => ({ content, progress: state.progress[content.id] }));

const summary = () => {
  const words = studyWords();
  return {
    total: words.length,
    retained: words.filter((word) => word.progress.isMemorized).length,
    mastered: words.filter((word) => word.progress.isMemorizedMax).length,
    review: words.filter((word) => !word.progress.isMemorizedMax && word.progress.memorizedAt < 100).length,
  };
};

const setRoute = (route, options = {}) => {
  if (options.selectedId) state.selectedId = options.selectedId;
  if (route === "test") resetTest(false);
  if (!options.replace) state.history.push(route);
  state.route = route;
  render();
};

const goBack = () => {
  if (state.route === "home") return;
  if (state.route === "detail") {
    state.route = "list";
  } else if (state.route === "test") {
    state.route = "list";
  } else {
    state.route = "home";
  }
  state.showBack = false;
  render();
};

const markKnown = (progress) => {
  const updated = { ...progress };
  if (!updated.isMemorized || updated.memorizedAt < 100) updated.memorizedCount += 1;
  updated.isMemorized = true;
  updated.isMemorizedMax = false;
  updated.memorizedAt = 100;
  return updated;
};

const markMastered = (progress) => {
  const updated = { ...progress };
  if (!updated.isMemorized) updated.memorizedCount += 1;
  updated.isMemorized = true;
  updated.isMemorizedMax = true;
  updated.memorizedAt = 100;
  return updated;
};

const markLearning = (progress) => ({
  ...progress,
  isMemorized: false,
  isMemorizedMax: false,
  memorizedAt: 0,
});

const toggleFlutterLike = (progress) => {
  if (progress.isMemorizedMax) return markLearning(progress);
  if (progress.isMemorized) return markMastered(progress);
  return markKnown(progress);
};

const updateProgress = (wordId, transform) => {
  state.progress[wordId] = transform(state.progress[wordId]);
};

